const assert = require('node:assert/strict');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const php = process.env.PHP_BIN || 'php';
const fixture = path.join(__dirname, 'andamento_route_fixture.php');
const render = (mode) => execFileSync(php, ['-d', 'extension=pdo_sqlite', fixture, mode], { encoding: 'utf8' });
const main = render('main');
assert(main.includes('Massimi e minimi per titolo'));
assert(main.includes('Storico quantit&agrave;'));
assert(main.includes('AZ'));
assert(!main.includes('BTP test'));
const quantity = render('quantity');
assert(quantity.includes('Storico quantit&agrave;'));
assert(quantity.includes('BTP test'));
assert(quantity.includes('+500'));
assert(quantity.includes('snapshot senza dato intermedio'));
const filtered = render('filtered');
assert(filtered.includes('BTP test'));
assert(filtered.includes('+500'));
assert(!filtered.includes('snapshot senza dato intermedio'));
console.log('OK: controller Andamento, filtro e storico BTP verificati su database sintetico isolato.');
