const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const os = require('node:os');
const { execFileSync } = require('node:child_process');
const php = process.env.PHP_BIN || 'php';
const fixture = path.join(__dirname, 'andamento_route_fixture.php');
const render = (mode) => execFileSync(php, ['-d', 'extension=pdo_sqlite', fixture, mode], { encoding: 'utf8' });
const main = render('main');
assert(main.includes('Massimi e minimi per titolo'));
assert(main.includes('Storico quantit&agrave;'));
assert(main.includes('AZ'));
assert(main.includes('BTP test') && main.includes('ETF test'));
assert(main.includes('value="all" selected'));
const etf = render('etf');
assert(etf.includes('ETF test') && !etf.includes('Azione test') && !etf.includes('BTP test'));
assert(etf.includes('value="ETF" selected') && etf.includes('export=xlsx&amp;asset_type=ETF'));
assert(etf.includes('2026-11-15') && etf.includes('2026-11-17'));
const btp = render('btp');
assert(btp.includes('BTP test') && !btp.includes('Azione test') && !btp.includes('ETF test'));
assert(btp.includes('>BTP-13GN27 VALORE SU</a>') && btp.includes('>BTP-13GN27 VALSU CUM</a>'));
assert(btp.includes('T54748.MOT') && btp.includes('T54739.MOT'));
const azione = render('azione');
assert(azione.includes('Azione test') && !azione.includes('BTP test') && !azione.includes('ETF test'));
const pac = render('pac');
assert(pac.includes('Nessun titolo della categoria selezionata') && pac.includes('value="PAC" selected'));
const invalid = render('invalid');
assert(invalid.includes('value="all" selected') && invalid.includes('BTP test'));
const quantity = render('quantity');
assert(quantity.includes('Storico quantit&agrave;'));
assert(quantity.includes('BTP test'));
assert(quantity.includes('+500'));
assert(quantity.includes('snapshot senza dato intermedio'));
const filtered = render('filtered');
assert(filtered.includes('BTP test'));
assert(filtered.includes('+500'));
assert(!filtered.includes('snapshot senza dato intermedio'));
const temporaryDir = fs.mkdtempSync(path.join(os.tmpdir(), 'andamento-xlsx-'));
const xlsxPath = path.join(temporaryDir, 'andamento.xlsx');
try {
    fs.writeFileSync(xlsxPath, execFileSync(php, ['-d', 'extension=pdo_sqlite', fixture, 'export-etf']));
    const autoload = path.join(__dirname, '..', 'vendor', 'autoload.php');
    const inspect = 'require $argv[1]; $s=\\PhpOffice\\PhpSpreadsheet\\IOFactory::load($argv[2])->getActiveSheet(); echo json_encode([$s->getCell("B4")->getValue(),$s->getCell("E4")->getValue(),$s->getCell("A6")->getValue(),$s->getCell("A8")->getValue(),$s->getCell("A2")->getValue()]);';
    const cells = JSON.parse(execFileSync(php, ['-r', inspect, autoload, xlsxPath], { encoding: 'utf8' }));
    assert.deepEqual(cells.slice(0, 4), ['ETF test (ETX)', null, '2026-11-17', '2026-11-15']);
    assert(cells[4].includes('Strumenti: ETF'));
} finally {
    if (fs.existsSync(xlsxPath)) fs.unlinkSync(xlsxPath);
    fs.rmdirSync(temporaryDir);
}
console.log('OK: filtro categorie, date, Excel e storico BTP verificati su database sintetico isolato.');
